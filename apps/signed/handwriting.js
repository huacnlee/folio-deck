const SLANT = 0.2;

/**
 * Writes `name` as strokes, slanted, with a light underline flourish.
 * @param {string} name
 * @returns {{ aspect: number, strokes: import("./signature.js").Stroke[] } | null}
 */
export function typedSignature(name) {
  /** @type {[number, number][][]} */
  const strokes = [];
  let x = 0;
  for (const char of name.trim()) {
    const glyph = GLYPHS[char] ?? GLYPHS[char.toLowerCase()] ?? GLYPHS[" "];
    const [advance, ...parts] = glyph;
    for (const flat of parts) {
      const stroke = [];
      for (let i = 0; i < flat.length; i += 2) stroke.push(/** @type {[number, number]} */ ([(x + flat[i] + (1 - flat[i + 1]) * SLANT) * 100, flat[i + 1] * 100]));
      strokes.push(stroke);
    }
    x += advance + 0.07;
  }
  if (!strokes.length) return null;
  const width = x * 100;
  strokes.push([[width * 0.08, 112], [width * 0.45, 110], [width * 0.8, 104], [width * 0.98, 100]]);
  return normalize(strokes);
}
